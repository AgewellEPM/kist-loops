#!/usr/bin/env python3
"""Render authenticated, self-contained launchers from bounded source modules."""
import argparse
import json
from pathlib import Path

DIRECTORY = Path(__file__).resolve().parent
ROOT = DIRECTORY.parents[1]
RESOURCE_TOKEN = "# @KIST_RESOURCE_PROTOCOL@\n"


def resource_protocol():
    module = (DIRECTORY / "resource_inventory.py").read_text()
    return ("# BEGIN GENERATED resource_inventory.py\nresource_python() {\n"
            "  resource_program=$(/bin/cat <<'KIST_RESOURCE_PY'\n" + module
            + '\nexec(compile(sys.stdin.buffer.read(), "<deployment>", "exec"))\n'
            + 'KIST_RESOURCE_PY\n  )\n  python_clean -c "$resource_program" "$@"\n}\n'
            + "# END GENERATED resource_inventory.py\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    parts = json.loads((DIRECTORY / "launcher_parts.json").read_text())
    if set(parts) != {"kist-rebuild", "kist-dashboard"}:
        raise SystemExit("unexpected launcher inventory")
    for name, paths in parts.items():
        components = []
        for relative in paths:
            path = DIRECTORY / relative
            if not path.resolve().is_relative_to(DIRECTORY) or path.is_symlink():
                raise SystemExit("unsafe launcher source path")
            component = path.read_text()
            if len(component.splitlines()) > 1000:
                raise SystemExit(f"split the source module before growing it: {path}")
            components.append(component)
        body = "".join(components)
        if body.count(RESOURCE_TOKEN) != 1:
            raise SystemExit("launcher must embed the resource protocol exactly once")
        body = body.replace(RESOURCE_TOKEN, resource_protocol())
        shebang, rest = body.split("\n", 1)
        expected = (shebang + "\n# Generated by scripts/deployment/render_launchers.py; edit its source modules.\n"
                    + "# Installed execution uses only this authenticated file, never checkout imports.\n" + rest)
        target = ROOT / "scripts" / name
        if args.check:
            if target.read_text() != expected:
                raise SystemExit(f"stale generated launcher: {target}")
        elif target.read_text() != expected:
            target.write_text(expected)


if __name__ == "__main__":
    main()
