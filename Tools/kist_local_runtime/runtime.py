#!/usr/bin/python3
"""Small Ollama gateway: serialize inference, enforce limits, reap every worker."""
import hashlib
import http.client
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
import os
from pathlib import Path
import re
import select
import signal
import socket
import subprocess
import threading
import time

ROOT = Path(__file__).resolve().parent
CONFIG = json.loads((ROOT / "config.json").read_text())
MODELS = Path(CONFIG["model_root"])
DISABLED = Path.home() / ".kist/local-ai-disabled"
INFERENCE = {"/api/chat", "/api/generate", "/api/embed", "/api/embeddings"}
INVENTORY_ERROR = None


class Rejected(Exception):
    pass


def pressure():
    try:
        result = subprocess.run(["/usr/sbin/sysctl", "-n",
                                 "kern.memorystatus_vm_pressure_level"],
                                capture_output=True, text=True, timeout=2, check=True)
        return int(result.stdout.strip())
    except (ValueError, OSError, subprocess.SubprocessError):
        return -1


def storage_ready():
    return Path("/Volumes/PRO-G40").is_mount() and MODELS.is_dir()


def scan_inventory():
    global INVENTORY_ERROR
    INVENTORY_ERROR = None
    if not storage_ready():
        return []
    base = MODELS / "manifests/registry.ollama.ai/library"
    models = []
    try:
        paths = [path for parent in base.iterdir() if parent.is_dir() for path in parent.iterdir()]
    except OSError as error:
        INVENTORY_ERROR = str(error)
        return []
    for path in paths:
        if not path.is_file() or path.is_symlink():
            continue
        try:
            raw = path.read_bytes()
            manifest = json.loads(raw)
            digest = manifest["config"]["digest"]
            if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
                continue
            config = json.loads((MODELS / "blobs" / digest.replace(":", "-")).read_text())
            name = f"{path.parent.name}:{path.name}"
            models.append({"name": name, "model": name,
                           "size": sum(layer["size"] for layer in manifest["layers"]) +
                                   manifest["config"].get("size", 0),
                           "digest": hashlib.sha256(raw).hexdigest(),
                           "modified_at": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                                        time.gmtime(path.stat().st_mtime)),
                           "details": {"format": config.get("model_format", "gguf"),
                                       "family": config.get("model_family", ""),
                                       "families": config.get("model_families", []),
                                       "parameter_size": config.get("model_type", ""),
                                       "quantization_level": config.get("file_type", "")}})
        except (OSError, ValueError, KeyError, TypeError) as error:
            INVENTORY_ERROR = str(error)
            continue
    return models


def inventory():
    # Generated by the explicit user command. LaunchAgents do not necessarily
    # inherit Terminal's removable-volume permission. The backend independently
    # verifies this snapshot through its native API before every model load.
    try:
        return json.loads((ROOT / "catalog.json").read_text())
    except (OSError, ValueError):
        return []


def prepare(body):
    if DISABLED.exists():
        raise Rejected("Local AI is switched off. Use cloud inference.")
    if not storage_ready():
        raise Rejected("PRO-G40 model storage is unavailable; no internal fallback.")
    model = body.get("model", "")
    if not isinstance(model, str):
        raise Rejected("A model name is required.")
    if ":" not in model:
        model += ":latest"
    entry = next((item for item in inventory() if item["name"] == model), None)
    if entry is None:
        raise Rejected("Model is not installed in the external local library. Use cloud inference.")
    if entry["size"] > CONFIG["max_model_bytes"]:
        raise Rejected("Model exceeds this Mac's 2 GiB local weight limit. Use cloud inference.")
    if pressure() != 1:
        raise Rejected("Mac memory is under pressure. Local inference refused; use cloud inference.")
    options = body.get("options") or {}
    if not isinstance(options, dict):
        raise Rejected("options must be an object.")
    options = dict(options)
    context = options.get("num_ctx", CONFIG["default_context_tokens"])
    output = options.get("num_predict", 512)
    if type(context) is not int or not 256 <= context <= CONFIG["context_tokens"]:
        raise Rejected("Local context must be 256–4096 tokens. Use cloud for larger requests.")
    if type(output) is not int or not 1 <= output <= CONFIG["max_output_tokens"]:
        raise Rejected("Local output must be capped at 1–1024 tokens.")
    if body.get("images") or any(isinstance(m, dict) and m.get("images")
                                 for m in body.get("messages", []) if isinstance(m, dict)):
        raise Rejected("Local vision is disabled in the lightweight Mac profile. Use cloud vision.")
    # Bound tool schemas and history as well as ordinary prompt text; never silently trim them.
    prompt_bytes = len(json.dumps({k: v for k, v in body.items()
                                 if k in ("messages", "prompt", "system", "input", "tools", "suffix")}))
    if prompt_bytes // 3 + output + 256 > context:
        raise Rejected("Request is too large for the lightweight context. Use cloud inference.")
    # Client options must not bypass host resource limits.
    safe_options = {k: v for k, v in options.items()
                    if k in ("temperature", "top_p", "top_k", "min_p", "seed",
                             "repeat_penalty", "stop")}
    safe_options.update(num_ctx=context, num_predict=output, num_thread=4)
    body.update(model=model, options=safe_options, keep_alive=0, think=False)
    return body


class Runtime:
    def __init__(self):
        self.slot = threading.Lock()
        self.process_lock = threading.Lock()
        self.child = None
        self.port = None
        self.active_model = None
        self.last_result = "idle"
        self.completed = 0
        self.shutting_down = threading.Event()

    def snapshot(self):
        return {"mode": "off" if DISABLED.exists() else "auto",
                "inventory_error": INVENTORY_ERROR,
                "busy": self.slot.locked(), "active_model": self.active_model,
                "worker_pid": self.child.pid if self.child else None,
                "last_result": self.last_result, "completed": self.completed,
                "max_model_bytes": CONFIG["max_model_bytes"],
                "context_limit": CONFIG["context_tokens"], "idle_workers": 0}

    def stop(self):
        with self.process_lock:
            child, self.child = self.child, None
            self.port = None
            if child is None:
                return
            # Each backend owns a new session; never signal the gateway's or another app's group.
            try:
                os.killpg(child.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
            try:
                child.wait(timeout=2)
            except subprocess.TimeoutExpired:
                pass
            try:
                os.killpg(child.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            child.wait(timeout=3)

    def start(self):
        with socket.socket() as reservation:
            reservation.bind(("127.0.0.1", 0))
            port = reservation.getsockname()[1]
        env = os.environ.copy()
        env.update(OLLAMA_HOST=f"127.0.0.1:{port}", OLLAMA_MODELS=str(MODELS),
                   OLLAMA_NO_CLOUD="1", OLLAMA_FLASH_ATTENTION="1",
                   OLLAMA_KV_CACHE_TYPE="q8_0", OLLAMA_CONTEXT_LENGTH="2048",
                   OLLAMA_MAX_LOADED_MODELS="1", OLLAMA_NUM_PARALLEL="1",
                   OLLAMA_MAX_QUEUE="1", OLLAMA_KEEP_ALIVE="0")
        with self.process_lock:
            if self.shutting_down.is_set() or DISABLED.exists():
                raise Rejected("Local runtime is stopping.")
            self.child = subprocess.Popen([CONFIG["ollama_bin"], "serve"], env=env,
                                          stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                          stderr=subprocess.DEVNULL, start_new_session=True)
            self.port = port
            child = self.child
        deadline = time.monotonic() + 10
        while time.monotonic() < deadline:
            if child.poll() is not None:
                raise Rejected("Private Ollama backend failed to start.")
            try:
                with socket.create_connection(("127.0.0.1", port), timeout=0.1):
                    return port
            except OSError:
                time.sleep(0.05)
        raise Rejected("Private Ollama backend startup timed out.")

    def watch(self, finished, is_inference, client):
        deadline = time.monotonic() + CONFIG["request_timeout_seconds"]
        while not finished.wait(0.5):
            try:
                disconnected = bool(select.select([client], [], [], 0)[0]) and not client.recv(1, socket.MSG_PEEK)
            except OSError:
                disconnected = True
            if disconnected:
                self.last_result = "stopped: client disconnected"
                self.stop()
                return
            if DISABLED.exists() or time.monotonic() >= deadline:
                self.last_result = "stopped: disabled or timed out"
                self.stop()
                return
            if is_inference and pressure() != 1:
                self.last_result = "stopped: memory pressure"
                self.stop()
                return


RUNTIME = Runtime()


class Handler(BaseHTTPRequestHandler):
    server_version = "KistLocalRuntime/1"

    def log_message(self, *_args):
        pass  # Do not persist prompts, images, or repeated background-client errors.

    def do_HEAD(self):
        self.send_response(200 if self.path == "/" else 404)
        self.send_header("Content-Length", "0")
        self.send_header("Connection", "close")
        self.end_headers()

    def reply(self, status, obj):
        data = json.dumps(obj).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Connection", "close")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if self.path == "/":
            self.reply(200, {"status": "Ollama on demand", "mode": "auto"})
        elif self.path == "/_kist/status":
            self.reply(200, RUNTIME.snapshot())
        elif self.path == "/api/tags":
            self.reply(200, {"models": [m for m in inventory()
                                        if m["size"] <= CONFIG["max_model_bytes"]]})
        elif self.path == "/api/ps":
            # Query an already running backend only; observation never starts one.
            port = RUNTIME.port
            if port is None:
                self.reply(200, {"models": []})
                return
            conn = http.client.HTTPConnection("127.0.0.1", port, timeout=2)
            try:
                conn.request("GET", "/api/ps")
                self.reply(200, json.loads(conn.getresponse().read()))
            except (OSError, ValueError, http.client.HTTPException):
                self.reply(200, {"models": []})
            finally:
                conn.close()
        elif self.path == "/api/version":
            version = Path(CONFIG["ollama_bin"]).resolve().parts
            self.reply(200, {"version": version[version.index("ollama") + 1]})
        else:
            self.reply(404, {"error": "Use the native Ollama API on this managed endpoint."})

    def do_POST(self):
        is_inference = self.path in INFERENCE
        if not is_inference and self.path != "/api/show":
            self.reply(403, {"error": "Downloads and model mutation are disabled in this lightweight profile."})
            return
        try:
            self.connection.settimeout(5)
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= 131072 or self.headers.get("Transfer-Encoding"):
                raise Rejected("Expected a JSON request no larger than 128 KiB.")
            raw = self.rfile.read(length)
            if len(raw) != length:
                raise Rejected("Incomplete request body.")
            body = json.loads(raw)
            if not isinstance(body, dict):
                raise Rejected("Expected a JSON object.")
            if is_inference:
                body = prepare(body)
            elif DISABLED.exists() or not storage_ready():
                raise Rejected("Local AI or external model storage is unavailable.")
            elif self.path == "/api/show":
                name = body.get("model", body.get("name", ""))
                if isinstance(name, str) and ":" not in name:
                    name += ":latest"
                entry = next((m for m in inventory() if m["name"] == name), None)
                if entry is None or entry["size"] > CONFIG["max_model_bytes"]:
                    raise Rejected("Model is outside the small-model profile; use cloud inference.")
        except (ValueError, TypeError, OSError, Rejected) as error:
            self.reply(503, {"error": str(error)})
            return
        if not RUNTIME.slot.acquire(blocking=False):
            self.reply(503, {"error": "One local request is already running. Use cloud inference; no queue."})
            return
        finished = threading.Event()
        watcher = None
        conn = None
        headers_sent = False
        try:
            RUNTIME.active_model = body.get("model") if is_inference else None
            RUNTIME.last_result = "running"
            port = RUNTIME.start()
            watcher = threading.Thread(target=RUNTIME.watch,
                                       args=(finished, is_inference, self.connection), daemon=True)
            watcher.start()
            if is_inference:
                check = http.client.HTTPConnection("127.0.0.1", port, timeout=4)
                try:
                    check.request("GET", "/api/tags")
                    available = json.loads(check.getresponse().read()).get("models", [])
                    actual = next((m for m in available if m.get("name") == body["model"]), None)
                    pinned = next(m for m in inventory() if m["name"] == body["model"])
                    if (actual is None or actual.get("size", float("inf")) > CONFIG["max_model_bytes"]
                            or actual.get("digest") != pinned["digest"]):
                        raise Rejected("Ollama could not verify the approved small model. No model loaded.")
                finally:
                    check.close()
            conn = http.client.HTTPConnection("127.0.0.1", port,
                                              timeout=CONFIG["request_timeout_seconds"] + 5)
            conn.request("POST", self.path, body=json.dumps(body).encode(),
                         headers={"Content-Type": "application/json"})
            response = conn.getresponse()
            self.send_response(response.status)
            self.send_header("Content-Type", response.getheader("Content-Type", "application/json"))
            self.send_header("Connection", "close")
            self.end_headers()
            headers_sent = True
            total = 0
            while True:
                chunk = response.read1(16384)
                if not chunk:
                    break
                total += len(chunk)
                if total > 8 * 1024 * 1024:
                    raise Rejected("Local response exceeded the output byte limit.")
                self.wfile.write(chunk)
                self.wfile.flush()
            if RUNTIME.last_result == "running":
                RUNTIME.last_result = f"HTTP {response.status}"
        except (OSError, http.client.HTTPException, Rejected) as error:
            if RUNTIME.last_result == "running":
                RUNTIME.last_result = "failed or client disconnected"
            if not headers_sent:
                try:
                    self.reply(503, {"error": str(error) or "Local worker stopped; use cloud inference."})
                except OSError:
                    pass
        finally:
            if conn:
                conn.close()
            finished.set()
            if watcher:
                watcher.join(timeout=6)
            RUNTIME.stop()
            RUNTIME.active_model = None
            RUNTIME.completed += 1
            RUNTIME.slot.release()


def main():
    if DISABLED.exists():
        raise SystemExit("Local AI is switched off; use kist-local-ai auto to enable it.")
    server = ThreadingHTTPServer(("127.0.0.1", CONFIG["listen_port"]), Handler)
    server.daemon_threads = True
    def stop(_signal, _frame):
        RUNTIME.shutting_down.set()
        threading.Thread(target=server.shutdown, daemon=True).start()
    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    try:
        server.serve_forever(poll_interval=0.1)
    finally:
        RUNTIME.stop()
        server.server_close()


if __name__ == "__main__":
    main()
